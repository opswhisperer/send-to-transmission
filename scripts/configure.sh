#!/usr/bin/env bash
# Writes Config/Local.xcconfig, the gitignored overlay that holds a developer's
# signing team and bundle identifier prefix on top of Config/Base.xcconfig.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL="$REPO_ROOT/Config/Local.xcconfig"
PROJECT="$REPO_ROOT/macOS/Send to Transmission/Send to Transmission.xcodeproj"

usage() {
    cat <<'EOF'
Usage: scripts/configure.sh [options]

Creates Config/Local.xcconfig (gitignored) so the project builds and signs with
your Apple Developer account. Nothing tracked by Git is modified.

  --team ID              Ten-character Team ID. Detected from your Apple
                         Development certificates when omitted.
  --local                No developer account: "Sign to Run Locally". Safari
                         then needs Develop → Allow Unsigned Extensions.
  --bundle-prefix PREFIX Reverse-DNS prefix you control, e.g. com.yourname.
                         Defaults to the existing overlay's value.
  --keychain-service S   Keychain service name for the RPC password.
                         Defaults to PREFIX.SendToTransmission.rpc.
  --list-teams           Print teams found in your keychain and exit.
  --show                 Print the effective signing settings and exit.
  --force                Overwrite an existing Config/Local.xcconfig.
  -h, --help             Show this help.

Examples:
  scripts/configure.sh --bundle-prefix com.yourname
  scripts/configure.sh --team ABCDE12345 --bundle-prefix com.yourname
  scripts/configure.sh --local --bundle-prefix com.yourname
EOF
}

die() { echo "Error: $*" >&2; exit 1; }

# Prints "TEAMID<TAB>Organization" for each Apple Development / Developer ID certificate.
list_teams() {
    local tmp
    tmp="$(mktemp -d "${TMPDIR:-/tmp}/configure-certs.XXXXXX")"
    for name in "Apple Development" "Developer ID Application"; do
        security find-certificate -a -c "$name" -p 2>/dev/null || true
    done | awk -v dir="$tmp" '/BEGIN CERTIFICATE/ { n++ } n { print > (dir "/" n ".pem") }'
    for pem in "$tmp"/*.pem; do
        [[ -e "$pem" ]] || continue
        openssl x509 -in "$pem" -noout -subject -nameopt sep_multiline,utf8 2>/dev/null |
            awk -F= '/^ *OU=/ { ou = $2 } /^ *O=/ { o = $2 } END { if (ou ~ /^[A-Z0-9]{10}$/) print ou "\t" o }'
    done | sort -u
    rm -rf "$tmp"
}

# Reads a setting from an xcconfig file, ignoring comments.
read_setting() {
    [[ -f "$2" ]] || return 0
    awk -v key="$1" '$0 !~ /^[[:space:]]*\/\// && $1 == key && $2 == "=" { $1 = $2 = ""; sub(/^ +/, ""); print; exit }' "$2"
}

show() {
    xcodebuild -project "$PROJECT" -scheme "Send to Transmission" -configuration Debug -showBuildSettings 2>/dev/null |
        awk '/^ +(DEVELOPMENT_TEAM|CODE_SIGN_IDENTITY|PRODUCT_BUNDLE_IDENTIFIER|TRANSMISSION_KEYCHAIN_SERVICE) = / && !seen[$0]++ { sub(/^ +/, ""); print }'
}

TEAM=""
LOCAL_SIGNING=false
PREFIX=""
SERVICE=""
FORCE=false
while (($#)); do
    case "$1" in
        --team) TEAM="${2:-}"; shift ;;
        --local) LOCAL_SIGNING=true ;;
        --bundle-prefix) PREFIX="${2:-}"; shift ;;
        --keychain-service) SERVICE="${2:-}"; shift ;;
        --list-teams) list_teams; exit 0 ;;
        --show) show; exit 0 ;;
        --force) FORCE=true ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; exit 2 ;;
    esac
    shift
done

if [[ -f "$LOCAL" && $FORCE == false ]]; then
    die "Config/Local.xcconfig already exists. Re-run with --force to replace it, or edit it directly."
fi

PREFIX="${PREFIX:-$(read_setting BUNDLE_ID_PREFIX "$LOCAL")}"
[[ -n "$PREFIX" ]] || die "pass --bundle-prefix, e.g. --bundle-prefix com.yourname."
[[ "$PREFIX" =~ ^[A-Za-z][A-Za-z0-9-]*(\.[A-Za-z0-9-]+)+$ ]] || die "bundle prefix must be reverse-DNS, e.g. com.yourname."
[[ "$PREFIX" != com.example ]] || die "choose a bundle prefix you control instead of com.example."

if $LOCAL_SIGNING; then
    [[ -z "$TEAM" ]] || die "--team and --local are mutually exclusive."
else
    if [[ -z "$TEAM" ]]; then
        teams="$(list_teams)"
        count="$(grep -c . <<< "$teams" || true)"
        if [[ "$count" -eq 1 ]]; then
            TEAM="$(cut -f1 <<< "$teams")"
            echo "Using team $TEAM ($(cut -f2 <<< "$teams")) from your Apple Development certificate."
        elif [[ "$count" -eq 0 ]]; then
            die "no Apple Development certificate found. Sign in under Xcode → Settings → Accounts and create one, pass --team, or use --local."
        else
            echo "Several teams found:" >&2
            sed 's/^/  /' <<< "$teams" >&2
            die "pass --team with one of them."
        fi
    fi
    [[ "$TEAM" =~ ^[A-Z0-9]{10}$ ]] || die "Team ID must be ten uppercase letters or digits."
fi

{
    echo "// Personal overlay for Config/Base.xcconfig. Gitignored; generated by scripts/configure.sh."
    echo
    if $LOCAL_SIGNING; then
        echo "DEVELOPMENT_TEAM ="
        echo "CODE_SIGN_IDENTITY = -"
    else
        echo "DEVELOPMENT_TEAM = $TEAM"
        echo "CODE_SIGN_IDENTITY = Apple Development"
    fi
    echo "BUNDLE_ID_PREFIX = $PREFIX"
    [[ -z "$SERVICE" ]] || echo "TRANSMISSION_KEYCHAIN_SERVICE = $SERVICE"
} > "$LOCAL"
echo "Wrote Config/Local.xcconfig"

echo
echo "Effective settings:"
show
